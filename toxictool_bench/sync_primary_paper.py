"""Rescore the complete primary suites without requiring unrelated historical runs."""
from __future__ import annotations

import hashlib
import json
import re
from collections import defaultdict
from pathlib import Path

from rebuild_paper_results import ROOT, RESULTS, DEFAULT_MANIFEST, load_manifest, rescore, write_bootstrap_table
from summarize_results import write_overall, write_poison, write_severity
from evaluator import aggregate
from build_public_paper_summaries import PAPER_ADAPTERS, read_rows, write_cross_model, write_poison_type


def table(path, label, rows):
    text = path.read_text()
    matches = list(re.finditer(r"\\begin\{table\*?\}.*?\\end\{table\*?\}", text, re.S))
    block = next(m for m in matches if r"\label{" + label + "}" in m.group())
    old = block.group()
    start = old.index(r"\midrule") + len(r"\midrule")
    end = old.index(r"\bottomrule", start)
    body = "\n% Generated by toxictool_bench/sync_primary_paper.py; do not edit numbers.\n" + "\n".join(rows) + "\n"
    path.write_text(text[:block.start()] + old[:start] + body + old[end:] + text[block.end():])


def line(*cells):
    return " & ".join(str(c) for c in cells) + r" \\"


def main():
    specs = [s for s in load_manifest(DEFAULT_MANIFEST) if s['experiment'] in {'cross_model', 'expanded_gpt'}]
    scored = [(s, rescore(s)) for s in specs]
    counts = {e: sum(len(rs) for s, rs in scored if s['experiment'] == e) for e in ('cross_model', 'expanded_gpt')}
    if counts != {'cross_model': 1460, 'expanded_gpt': 720}:
        raise ValueError(f'Incomplete primary suite: {counts}')
    grouped = defaultdict(list)
    for s, rs in scored:
        for r in rs:
            grouped[s['experiment'], s['suite'], r['model'], r['adapter']].append(r)
    for key, rs in grouped.items():
        expected = 60 if key[0] == 'expanded_gpt' else (34 if key[1] == 'numerical' else 24)
        ids = [[r['task_id'] for r in rs if r['environment'] == env] for env in ('clean', 'toxic')]
        if any(len(x) != expected or len(set(x)) != expected for x in ids) or set(ids[0]) != set(ids[1]):
            raise ValueError(f'Incomplete or duplicate task pairs: {key}')
    for suite, prefix in [('numerical', 'cross_model'), ('semantic_schema', 'semantic_schema_cross_model')]:
        rs = [r for s, rows in scored if s['experiment'] == 'cross_model' and s['suite'] == suite for r in rows]
        write_overall(rs, RESULTS / f'{prefix}_summary.csv')
        write_poison(rs, RESULTS / ('poison_type_summary.csv' if suite == 'numerical' else f'{prefix}_poison_summary.csv'))
        write_severity(rs, RESULTS / f'{prefix}_severity_summary.csv')
        write_bootstrap_table([(s, rows) for s, rows in scored if s['experiment'] == 'cross_model' and s['suite'] == suite],
                              RESULTS / f'{suite}_cross_model_bootstrap_ci.csv', 2000, 13 if suite == 'numerical' else 113)
        write_cross_model(read_rows(RESULTS / f'{prefix}_summary.csv', PAPER_ADAPTERS),
                          RESULTS / f'public_cross_model_{suite}_summary.csv', suite)
    write_poison_type(read_rows(RESULTS / 'poison_type_summary.csv', PAPER_ADAPTERS), RESULTS / 'public_poison_type_summary.csv')
    for suite in ('numerical', 'semantic_schema', 'combined'):
        rs = [r for s, rows in scored if s['experiment'] == 'expanded_gpt' and (suite == 'combined' or s['suite'] == suite) for r in rows]
        prefix = f'iclr2027_gpt_expanded_cross_agent_{suite}'
        write_overall(rs, RESULTS / f'{prefix}_summary.csv')
        write_poison(rs, RESULTS / f'{prefix}_poison_summary.csv')
        write_severity(rs, RESULTS / f'{prefix}_severity_summary.csv')
    def rates(rs):
        c = aggregate([r for r in rs if r['environment'] == 'clean'])
        t = aggregate([r for r in rs if r['environment'] == 'toxic'])
        return c, t
    names = {'langgraph_react_full': 'LangGraph ReAct', 'smolagents_toolcalling': 'smolagents',
             'pandasai_dataframe': 'PandasAI', 'autogen_tool_agent': 'AutoGen', 'da_agent_full': 'DA-Agent'}
    path = ROOT / 'sections/05_experiments.tex'
    rows = []
    for model, name in [('gpt-5.4-mini', 'GPT-5.4-mini'), ('claude-sonnet-4-6', 'Claude Sonnet 4.6'),
                        ('Qwen3.6-35B-A3B-no-thinking', 'Qwen3.6-35B')]:
        if rows: rows.append(r'\midrule')
        for i, (adapter, label) in enumerate(names.items()):
            cells = []
            for suite in ('numerical', 'semantic_schema'):
                rs = grouped.get(('cross_model', suite, model, adapter))
                if not rs: cells.extend(['--'] * 3); continue
                c, t = rates(rs)
                cells.extend(f'{v:.2f}' for v in (c['task_success'], t['task_success'], t['blind_compliance']))
            if set(cells) == {'--'}: continue
            rows.append(line(name if i == 0 else '', label, *cells))
    table(path, 'tab:cross-agent-model-full', rows)
    rows = []
    summary = []
    for adapter in ('langgraph_react_full', 'smolagents_toolcalling', 'autogen_tool_agent'):
        rs = [r for k, group in grouped.items() if k[0] == 'expanded_gpt' and k[3] == adapter for r in group]
        c, t = rates(rs)
        values = (c['task_success'], t['task_success'], c['task_success'] - t['task_success'],
                  t['blind_compliance'], t['recovery'], t['poison_delivery_rate'])
        summary.append(values)
        rows.append(line(names[adapter], *(f'{v:.2f}' for v in values)))
    table(path, 'tab:gpt-expanded-cross-agent-120', rows)
    ranges = [f'{min(v[i] for v in summary):.2f}--{max(v[i] for v in summary):.2f}' for i in range(3)]
    abstract = ROOT / 'sections/00_abstract.tex'
    abstract.write_text(re.sub(r'clean task success of [\d.]+--[\d.]+ falls to [\d.]+--[\d.]+',
                              f'clean task success of {ranges[0]} falls to {ranges[1]}', abstract.read_text()))
    text = re.sub(r'poisoned TSR falls by [\d.]+--[\d.]+', f'poisoned TSR falls by {ranges[2]}', path.read_text())
    import csv
    ci = next(r for r in csv.DictReader(open(RESULTS / 'numerical_cross_model_bootstrap_ci.csv'))
              if r['model'] == 'gpt-5.4-mini' and r['adapter'] == 'langgraph_react_full')
    text = re.sub(r'numerical BCR is [\d.]+ \[[\d.]+, [\d.]+\]',
                  'numerical BCR is {:.2f} [{:.2f}, {:.2f}]'.format(*(float(ci[k]) for k in ('toxic_bcr', 'toxic_bcr_lo', 'toxic_bcr_hi'))), text)
    ops = {r['poison_type']: r for r in csv.DictReader(open(RESULTS / 'public_poison_type_summary.csv'))}
    text = re.sub(r'\(\d+\.\d+ and \d+\.\d+\); sign flips are more visible and produce BCR \d+\.\d+\.?',
                  '({:.2f} and {:.2f}); sign flips are more visible and produce BCR {:.2f}.'.format(
                      *(float(ops[k]['bcr']) for k in ('aggregate_scale', 'rank_swap', 'sign_flip'))), text)
    path.write_text(text)
    inputs = {DEFAULT_MANIFEST, Path(__file__).resolve(), ROOT / 'toxictool_bench/evaluator.py',
              ROOT / 'toxictool_bench/rebuild_paper_results.py', ROOT / 'toxictool_bench/summarize_results.py',
              ROOT / 'toxictool_bench/bootstrap_ci.py', ROOT / 'toxictool_bench/build_public_paper_summaries.py'}
    for s in specs:
        inputs.add(ROOT / s['source'])
        inputs.update(ROOT / p for p in s['tasks'].split(';'))
    provenance = {'rows': counts, 'bootstrap_iterations': 2000, 'inputs': {
        str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(inputs)}}
    (RESULTS / 'primary_analysis_provenance.json').write_text(json.dumps(provenance, indent=2) + '\n')
    print(f'Synchronized primary results: {counts}')


if __name__ == '__main__':
    main()
